#!/usr/bin/env python3
"""Build deterministic, provenance-aware MySQL imports for open case-law datasets."""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import re
from collections import Counter
from pathlib import Path
from typing import Any, Iterable, Iterator


COLUMNS = [
    "title",
    "case_no",
    "court",
    "judge_date",
    "case_type",
    "summary",
    "holding",
    "procedure",
    "content",
    "jurisdiction",
    "language_code",
    "status",
    "source_dataset",
    "source_item_id",
    "source_url",
    "license_name",
    "metadata",
]

SCOTUS_ISSUE_AREAS = [
    "Criminal Procedure",
    "Civil Rights",
    "First Amendment",
    "Due Process",
    "Privacy",
    "Attorneys",
    "Unions",
    "Economic Activity",
    "Judicial Power",
    "Federalism",
    "Interstate Relations",
    "Federal Taxation",
    "Miscellaneous",
    "Private Action",
]

ECTHR_ARTICLES = [
    "Article 2",
    "Article 3",
    "Article 5",
    "Article 6",
    "Article 8",
    "Article 9",
    "Article 10",
    "Article 11",
    "Article 14",
    "Article 1 of Protocol 1",
    "No violation",
]


def clean_text(value: Any) -> str:
    text = str(value or "").replace("\r\n", "\n").replace("\r", "\n")
    return re.sub(r"[ \t]+\n", "\n", text).strip()


def compact_text(value: Any) -> str:
    return re.sub(r"\s+", " ", clean_text(value)).strip()


def sql_string(value: Any) -> str:
    if value is None:
        return "NULL"
    text = str(value)
    text = (
        text.replace("\\", "\\\\")
        .replace("\0", "\\0")
        .replace("\x1a", "\\Z")
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        .replace("'", "''")
    )
    return f"'{text}'"


def json_text(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), default=str)


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        for chunk in iter(lambda: file.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def stable_text_id(prefix: str, text: str) -> str:
    return f"{prefix}:{hashlib.sha256(text.encode('utf-8')).hexdigest()}"


def write_sql(output: Path, rows: Iterable[dict[str, Any]], batch_size: int = 10) -> dict[str, Any]:
    output.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    max_content = 0
    jurisdictions: Counter[str] = Counter()
    batch: list[str] = []
    column_sql = ", ".join(f"`{column}`" for column in COLUMNS)

    with output.open("wb") as raw_file:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw_file, compresslevel=9, mtime=0) as gz_file:
            def write(text: str) -> None:
                gz_file.write(text.encode("utf-8"))

            write("-- Generated by scripts/build-legal-case-datasets.py\nSET NAMES utf8mb4;\n")
            for row in rows:
                row["summary"] = clean_text(row.get("summary")) or clean_text(row.get("content"))[:2000]
                row["content"] = clean_text(row.get("content")) or row["summary"]
                row["metadata"] = json_text(row.get("metadata") or {})
                values = ", ".join(sql_string(row.get(column)) for column in COLUMNS)
                batch.append(f"({values})")
                count += 1
                max_content = max(max_content, len(row["content"]))
                jurisdictions[clean_text(row.get("jurisdiction"))] += 1
                if len(batch) >= batch_size:
                    write(
                        f"INSERT IGNORE INTO case_info ({column_sql}) VALUES\n"
                        + ",\n".join(batch)
                        + ";\n"
                    )
                    batch.clear()
            if batch:
                write(
                    f"INSERT IGNORE INTO case_info ({column_sql}) VALUES\n"
                    + ",\n".join(batch)
                    + ";\n"
                )

    return {
        "records": count,
        "jurisdictions": dict(sorted(jurisdictions.items())),
        "maximumContentCharacters": max_content,
        "output": str(output),
        "compressedBytes": output.stat().st_size,
        "sha256": file_sha256(output),
    }


def chinese_case_number(text: str) -> str | None:
    match = re.search(r"[（(]\d{4}[）)][^\s，。；]{1,40}?号", text)
    return compact_text(match.group(0)) if match else None


def chinese_court(text: str) -> str | None:
    match = re.search(r"([\u4e00-\u9fff]{2,40}?(?:人民法院|军事法院|海事法院|知识产权法院))", text[:1000])
    return compact_text(match.group(1)) if match else None


def chinese_procedure(title: str) -> str | None:
    for value in ("再审", "二审", "一审", "终审"):
        if value in title:
            return value
    return None


def joined_sections(sections: list[tuple[str, Any]]) -> str:
    parts = []
    for heading, value in sections:
        values = value if isinstance(value, list) else [value]
        text = "\n".join(clean_text(item) for item in values if clean_text(item))
        if text:
            parts.append(f"【{heading}】\n{text}")
    return "\n\n".join(parts)


def guiding_case_rows(directory: Path) -> Iterator[dict[str, Any]]:
    for path in sorted(directory.glob("guiding-*.json")):
        item = json.loads(path.read_text(encoding="utf-8"))
        if not item.get("id") or not item.get("title"):
            continue
        content = joined_sections([
            ("裁判要点", item.get("gist")),
            ("基本案情", item.get("facts")),
            ("裁判结果", item.get("result")),
            ("裁判理由", item.get("reasoning")),
            ("相关法条", item.get("relatedLaws")),
        ])
        title = clean_text(item.get("title"))
        yield {
            "title": title,
            "case_no": chinese_case_number(content + "\n" + title),
            "court": "最高人民法院（指导性案例）",
            "judge_date": None,
            "case_type": "指导性案例",
            "summary": "\n".join(clean_text(value) for value in item.get("gist", []) if clean_text(value)),
            "holding": "\n".join(clean_text(value) for value in item.get("result", []) if clean_text(value)) or None,
            "procedure": chinese_procedure(title),
            "content": content,
            "jurisdiction": "CN",
            "language_code": "zh-CN",
            "status": "published-guiding-case",
            "source_dataset": "Chinese-Law-Corpus-Guiding-Cases",
            "source_item_id": clean_text(item.get("id")),
            "source_url": clean_text(item.get("sourceUrl")) or "https://github.com/lttxzmj/chinese-law-corpus",
            "license_name": "CC0-1.0",
            "metadata": {
                "guidingCaseNumber": item.get("number"),
                "issuedLine": item.get("issuedLine"),
                "publishedAt": item.get("publishedAt"),
                "keywords": item.get("keywords") or [],
                "relatedLaws": item.get("relatedLaws") or [],
            },
        }


def gazette_case_rows(directory: Path) -> Iterator[dict[str, Any]]:
    for path in sorted(directory.glob("gazette-*.json")):
        item = json.loads(path.read_text(encoding="utf-8"))
        if not item.get("id") or not item.get("title"):
            continue
        body = "\n".join(clean_text(value) for value in item.get("body", []) if clean_text(value))
        summary = "\n".join(clean_text(value) for value in item.get("summary", []) if clean_text(value))
        title = clean_text(item.get("title"))
        yield {
            "title": title,
            "case_no": clean_text(item.get("caseNumber")) or chinese_case_number(body + "\n" + title),
            "court": clean_text(item.get("court")) or chinese_court(body),
            "judge_date": None,
            "case_type": clean_text(item.get("category")) or "最高人民法院公报案例",
            "summary": summary,
            "holding": summary or None,
            "procedure": clean_text(item.get("docType")) or chinese_procedure(title),
            "content": body,
            "jurisdiction": "CN",
            "language_code": "zh-CN",
            "status": "published-gazette-case",
            "source_dataset": "Chinese-Law-Corpus-Gazette-Cases",
            "source_item_id": clean_text(item.get("id")),
            "source_url": clean_text(item.get("sourceUrl")) or "https://github.com/lttxzmj/chinese-law-corpus",
            "license_name": "CC0-1.0",
            "metadata": {
                "issueYear": item.get("issueYear"),
                "issueNumber": item.get("issueNo"),
                "documentType": item.get("docType"),
            },
        }


def parquet_rows(files: list[Path]) -> Iterator[tuple[dict[str, Any], str, int]]:
    import pyarrow.parquet as parquet

    for path in files:
        split = path.stem.rsplit("-", 1)[-1]
        reader = parquet.ParquetFile(path)
        row_index = 0
        for batch in reader.iter_batches(batch_size=512):
            for item in batch.to_pylist():
                yield item, split, row_index
                row_index += 1


def class_names(labels: Any, names: list[str]) -> list[str]:
    values = labels if isinstance(labels, list) else [labels]
    result = []
    for value in values:
        try:
            index = int(value)
        except (TypeError, ValueError):
            result.append(str(value))
            continue
        result.append(names[index] if 0 <= index < len(names) else str(index))
    return result


def scotus_rows(files: list[Path]) -> Iterator[dict[str, Any]]:
    for item, split, row_index in parquet_rows(files):
        text = clean_text(item.get("text"))
        source_id = stable_text_id("opinion", text)
        issue_areas = class_names(item.get("label"), SCOTUS_ISSUE_AREAS)
        first_line = next((compact_text(line) for line in text.splitlines() if compact_text(line)), "")
        title = first_line[:1000] if first_line else f"SCOTUS opinion {source_id[-12:]}"
        yield {
            "title": title,
            "case_no": None,
            "court": "Supreme Court of the United States",
            "judge_date": None,
            "case_type": issue_areas[0] if issue_areas else "Supreme Court opinion",
            "summary": text[:3000],
            "holding": None,
            "procedure": "court opinion",
            "content": text,
            "jurisdiction": "US",
            "language_code": "en",
            "status": "historical-benchmark-corpus",
            "source_dataset": "LexGLUE-SCOTUS",
            "source_item_id": source_id,
            "source_url": "https://huggingface.co/datasets/coastalcph/lex_glue",
            "license_name": "CC-BY-4.0",
            "metadata": {"issueAreas": issue_areas, "datasetSplit": split, "datasetRow": row_index},
        }


def ecthr_rows(files: list[Path]) -> Iterator[dict[str, Any]]:
    for item, split, row_index in parquet_rows(files):
        paragraphs = item.get("text") if isinstance(item.get("text"), list) else [item.get("text")]
        paragraphs = [clean_text(value) for value in paragraphs if clean_text(value)]
        text = "\n\n".join(paragraphs)
        text_hash = hashlib.sha256(text.encode("utf-8")).hexdigest()
        source_id = f"facts:{split}:{row_index}:{text_hash}"
        articles = class_names(item.get("labels") or [], ECTHR_ARTICLES)
        yield {
            "title": f"ECtHR case facts {source_id[-12:]}",
            "case_no": None,
            "court": "European Court of Human Rights",
            "judge_date": None,
            "case_type": "Human rights",
            "summary": paragraphs[0] if paragraphs else text[:3000],
            "holding": ", ".join(articles) or None,
            "procedure": "case facts",
            "content": text,
            "jurisdiction": "ECHR",
            "language_code": "en",
            "status": "historical-benchmark-corpus",
            "source_dataset": "LexGLUE-ECtHR-A",
            "source_item_id": source_id,
            "source_url": "https://huggingface.co/datasets/coastalcph/lex_glue",
            "license_name": "CC-BY-4.0",
            "metadata": {
                "violatedArticles": articles,
                "datasetSplit": split,
                "datasetRow": row_index,
                "textSha256": text_hash,
            },
        }


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--china-corpus-root", type=Path, required=True)
    parser.add_argument("--scotus-parquet", type=Path, action="append", required=True)
    parser.add_argument("--ecthr-parquet", type=Path, action="append", required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    datasets = {
        "Chinese-Law-Corpus-Guiding-Cases": write_sql(
            args.output_dir / "lexaid-cases-cn-guiding.sql.gz",
            guiding_case_rows(args.china_corpus_root / "guiding-cases"),
        ),
        "Chinese-Law-Corpus-Gazette-Cases": write_sql(
            args.output_dir / "lexaid-cases-cn-gazette.sql.gz",
            gazette_case_rows(args.china_corpus_root / "gazette-cases"),
        ),
        "LexGLUE-ECtHR-A": write_sql(
            args.output_dir / "lexaid-cases-echr.sql.gz", ecthr_rows(args.ecthr_parquet)
        ),
    }
    for parquet_file in args.scotus_parquet:
        split = parquet_file.stem.rsplit("-", 1)[-1]
        datasets[f"LexGLUE-SCOTUS/{split}"] = write_sql(
            args.output_dir / f"lexaid-cases-us-{split}.sql.gz", scotus_rows([parquet_file])
        )
    manifest = {
        "generatedBy": "scripts/build-legal-case-datasets.py",
        "datasets": datasets,
        "licenses": {
            "Chinese-Law-Corpus-Guiding-Cases": "CC0-1.0",
            "Chinese-Law-Corpus-Gazette-Cases": "CC0-1.0",
            "LexGLUE-SCOTUS": "CC-BY-4.0",
            "LexGLUE-ECtHR-A": "CC-BY-4.0",
        },
        "totalRecords": sum(value["records"] for value in datasets.values()),
    }
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
