// This check creates a learner and an exam in a disposable LexAid database.
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const path = require('node:path')
const { createRequire } = require('node:module')
const { chromium } = createRequire(path.join(__dirname, '../frontend/package.json'))('playwright')
const base = process.env.LEXAID_LEARNING_TEST_BASE
if (!base) throw new Error('Set LEXAID_LEARNING_TEST_BASE to a frontend backed by a disposable database.')

async function main() {
  const browser = await chromium.launch({ executablePath: process.env.SMOKE_EXECUTABLE })
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
    const credentials = { username: 'practice_' + randomUUID().slice(0, 10), password: randomUUID() }
    const registration = await page.request.post(base + '/api/auth/register', { data: credentials })
    assert.equal((await registration.json()).code, 200)
    await page.goto(base + '/login')
    await page.locator('#login-username').fill(credentials.username)
    await page.locator('#login-password').fill(credentials.password)
    await page.locator('button.submit:visible').click()
    await page.waitForURL('**/dashboard')
    const pathSelector = page.getByRole('combobox', { name: '学习专题' })
    await pathSelector.selectOption({ label: '合同违约责任' })
    await page.getByRole('link', { name: /读法条/ }).click()
    await page.waitForURL('**/provisions/13')
    await page.getByRole('button', { name: /违约责任形式不包括/ }).click()
    await page.waitForURL('**/exam/run/*')
    await page.getByText('当事人一方不履行合同义务', { exact: false }).first().waitFor()
    await page.goto(base + '/dashboard')
    await page.getByRole('button', { name: /做同考点练习/ }).click()
    await page.getByText('关于正当防卫，下列说法正确的是？', { exact: true }).waitFor()
    await page.locator('.options label').filter({ hasText: /^\s*B\./ }).click()
    await page.getByRole('button', { name: '交 卷' }).click()
    await page.locator('.el-message-box__btns .el-button--primary').click()
    await page.waitForURL('**/exam/result/*')
    await page.getByRole('button', { name: 'AI 复盘本次作答' }).click()
    await page.waitForURL(url => url.pathname === '/ai-chat' && url.searchParams.get('contextType') === 'EXAM')
    await page.goto(base + '/wrong-book')
    await page.getByRole('button', { name: /情景迁移/ }).first().click()
    const dialog = page.getByRole('dialog', { name: '情景迁移练习' })
    await dialog.getByRole('radio').first().waitFor()
    assert.equal(await dialog.locator('.feedback').count(), 0)
    await dialog.locator('input[value="B"]').check()
    await dialog.getByRole('button', { name: '提交答案' }).click()
    await dialog.locator('.feedback').waitFor()
    console.log('Topic selection, precise question, exam feedback, context-bound AI and wrong-question transfer passed.')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error.message); process.exitCode = 1 })
