#!/usr/bin/env python3
"""Build reproducible MySQL imports for public Chinese and international legislation."""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import re
from collections import Counter
from datetime import datetime
from pathlib import Path
from typing import Any, Iterable, Iterator
from xml.etree import ElementTree as ET


COLUMNS = [
    "law_name",
    "category",
    "chapter",
    "article_no",
    "content",
    "effective_date",
    "issuing_authority",
    "jurisdiction",
    "language_code",
    "status",
    "source_dataset",
    "source_item_id",
    "source_url",
    "license_name",
    "promulgation_date",
    "metadata",
]

USLM_NAMESPACE = "http://xml.house.gov/schemas/uslm/1.0"
USLM = f"{{{USLM_NAMESPACE}}}"


def clean_text(value: Any) -> str:
    return re.sub(r"[ \t]+\n", "\n", str(value or "").replace("\r\n", "\n").replace("\r", "\n")).strip()


def compact_text(value: Any) -> str:
    return re.sub(r"\s+", " ", clean_text(value)).strip()


def iso_date(value: Any) -> str | None:
    text = clean_text(value)
    if not text:
        return None
    match = re.match(r"(\d{4}-\d{2}-\d{2})", text)
    if match:
        try:
            return datetime.strptime(match.group(1), "%Y-%m-%d").date().isoformat()
        except ValueError:
            return None
    return None


def eu_publication_date(text: str) -> str | None:
    match = re.match(r"\s*(\d{1,2})\.(\d{1,2})\.(\d{4})\b", text)
    if not match:
        return None
    try:
        return datetime(int(match.group(3)), int(match.group(2)), int(match.group(1))).date().isoformat()
    except ValueError:
        return None


def sql_string(value: Any) -> str:
    if value is None:
        return "NULL"
    text = str(value)
    text = (
        text.replace("\\", "\\\\")
        .replace("\0", "\\0")
        .replace("\x1a", "\\Z")
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        .replace("'", "''")
    )
    return f"'{text}'"


def json_text(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def write_sql(output: Path, rows: Iterable[dict[str, Any]], batch_size: int = 25) -> dict[str, Any]:
    output.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    empty_content = 0
    maximum_content_chars = 0
    categories: Counter[str] = Counter()
    jurisdictions: Counter[str] = Counter()
    batch: list[str] = []

    with output.open("wb") as raw_file:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw_file, compresslevel=9, mtime=0) as gz_file:
            def write(text: str) -> None:
                gz_file.write(text.encode("utf-8"))

            write("-- Generated by scripts/build-legal-code-datasets.py\nSET NAMES utf8mb4;\n")
            for row in rows:
                content = clean_text(row.get("content"))
                if not content:
                    empty_content += 1
                    content = clean_text(row.get("law_name"))
                row["content"] = content
                row["metadata"] = json_text(row.get("metadata") or {})
                values = ", ".join(sql_string(row.get(column)) for column in COLUMNS)
                batch.append(f"({values})")
                count += 1
                maximum_content_chars = max(maximum_content_chars, len(content))
                categories[clean_text(row.get("category"))] += 1
                jurisdictions[clean_text(row.get("jurisdiction"))] += 1
                if len(batch) >= batch_size:
                    write(
                        f"INSERT IGNORE INTO legal_provision ({', '.join(COLUMNS)}) VALUES\n"
                        + ",\n".join(batch)
                        + ";\n"
                    )
                    batch.clear()
            if batch:
                write(
                    f"INSERT IGNORE INTO legal_provision ({', '.join(COLUMNS)}) VALUES\n"
                    + ",\n".join(batch)
                    + ";\n"
                )

    return {
        "records": count,
        "emptyContentReplacedWithTitle": empty_content,
        "maximumContentCharacters": maximum_content_chars,
        "categories": dict(sorted(categories.items())),
        "jurisdictions": dict(sorted(jurisdictions.items())),
        "output": str(output),
        "compressedBytes": output.stat().st_size,
        "sha256": file_sha256(output),
    }


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        for chunk in iter(lambda: file.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def china_rows(directory: Path) -> Iterator[dict[str, Any]]:
    for file in sorted(directory.glob("*.json")):
        data = json.loads(file.read_text(encoding="utf-8"))
        if not isinstance(data, dict) or not isinstance(data.get("articles"), list):
            continue
        for article in data["articles"]:
            article_id = clean_text(article.get("id"))
            if not article_id:
                continue
            path = article.get("path") if isinstance(article.get("path"), list) else []
            yield {
                "law_name": clean_text(data.get("title")),
                "category": clean_text(data.get("category")) or "中国法律法规",
                "chapter": " · ".join(clean_text(item) for item in path if clean_text(item)) or None,
                "article_no": clean_text(article.get("displayNumber")) or str(article.get("articleNumber") or ""),
                "content": clean_text(article.get("text")),
                "effective_date": iso_date(data.get("effectiveDate")),
                "issuing_authority": clean_text(data.get("issuingAuthority")) or None,
                "jurisdiction": "CN",
                "language_code": "zh-CN",
                "status": clean_text(data.get("status")) or None,
                "source_dataset": "Chinese-Law-Corpus",
                "source_item_id": article_id,
                "source_url": f"https://github.com/lttxzmj/chinese-law-corpus/blob/master/laws/{file.name}",
                "license_name": "CC0-1.0",
                "promulgation_date": iso_date(data.get("promulgationDate")),
                "metadata": {
                    "lawId": data.get("id"),
                    "officialId": data.get("officialId"),
                    "articleNumber": article.get("articleNumber"),
                    "order": article.get("order"),
                },
            }


def uk_category(value: Any) -> str:
    return {
        "primary": "英国主要立法",
        "secondary": "英国次级立法",
        "euretained": "英国保留欧盟法",
    }.get(clean_text(value), "英国立法")


def uk_rows(parquet_file: Path) -> Iterator[dict[str, Any]]:
    import pyarrow.parquet as parquet

    occurrences: Counter[str] = Counter()
    parquet_reader = parquet.ParquetFile(parquet_file)
    for record_batch in parquet_reader.iter_batches(batch_size=2048):
        for item in record_batch.to_pylist():
            official_id = clean_text(item.get("id"))
            occurrence = occurrences[official_id]
            occurrences[official_id] += 1
            source_key = hashlib.sha256(f"{official_id}#{occurrence}".encode("utf-8")).hexdigest()
            source_url = official_id.replace("http://", "https://").replace("/id/", "/")
            citation_parts = [clean_text(item.get("type")), str(item.get("year") or ""), str(item.get("number") or "")]
            citation = "/".join(part for part in citation_parts if part)
            yield {
                "law_name": clean_text(item.get("title")) or official_id or "Untitled UK legislation",
                "category": uk_category(item.get("category")),
                "chapter": None,
                "article_no": citation or "Document",
                "content": clean_text(item.get("description")),
                "effective_date": iso_date(item.get("valid_date")) or iso_date(item.get("enactment_date")),
                "issuing_authority": clean_text(item.get("publisher")) or "The National Archives",
                "jurisdiction": "GB",
                "language_code": "en",
                "status": clean_text(item.get("status")) or None,
                "source_dataset": "UK-LexAPI-2026-11-01",
                "source_item_id": source_key,
                "source_url": source_url or "https://www.legislation.gov.uk/",
                "license_name": "Open-Government-Licence-3.0",
                "promulgation_date": iso_date(item.get("enactment_date")),
                "metadata": {
                    "officialId": official_id,
                    "duplicateOccurrence": occurrence,
                    "type": item.get("type"),
                    "year": item.get("year"),
                    "number": item.get("number"),
                    "extent": item.get("extent") or [],
                    "modifiedDate": item.get("modified_date"),
                    "numberOfProvisions": item.get("number_of_provisions"),
                    "provenance": {
                        "source": item.get("provenance_source"),
                        "model": item.get("provenance_model"),
                        "promptVersion": item.get("provenance_prompt_version"),
                        "timestamp": item.get("provenance_timestamp"),
                        "responseId": item.get("provenance_response_id"),
                    },
                },
            }


def eu_category(celex_id: str) -> str:
    kind = celex_id[5:6].upper() if len(celex_id) > 5 else ""
    return {
        "R": "欧盟条例",
        "L": "欧盟指令",
        "D": "欧盟决定",
    }.get(kind, "欧盟立法")


def eu_rows(parquet_files: list[Path]) -> Iterator[dict[str, Any]]:
    import pyarrow.parquet as parquet

    for parquet_file in parquet_files:
        parquet_reader = parquet.ParquetFile(parquet_file)
        for record_batch in parquet_reader.iter_batches(batch_size=1024):
            for item in record_batch.to_pylist():
                celex_id = clean_text(item.get("celex_id"))
                if not celex_id:
                    continue
                text = clean_text(item.get("text"))
                publication_date = eu_publication_date(text)
                yield {
                    "law_name": clean_text(item.get("title")) or f"EUR-Lex {celex_id}",
                    "category": eu_category(celex_id),
                    "chapter": None,
                    "article_no": celex_id,
                    "content": text,
                    "effective_date": None,
                    "issuing_authority": "European Union",
                    "jurisdiction": "EU",
                    "language_code": "en",
                    "status": "historical-corpus-1958-2016",
                    "source_dataset": "EURLEX57K",
                    "source_item_id": celex_id,
                    "source_url": f"https://eur-lex.europa.eu/legal-content/EN/TXT/?uri=CELEX:{celex_id}",
                    "license_name": "CC-BY-SA-4.0",
                    "promulgation_date": publication_date,
                    "metadata": {
                        "celexId": celex_id,
                        "eurovocConcepts": item.get("eurovoc_concepts") or [],
                        "datasetSplit": parquet_file.stem.removeprefix("eurlex-"),
                    },
                }


def direct_child_text(element: ET.Element, name: str) -> str:
    child = element.find(f"{USLM}{name}")
    return compact_text("".join(child.itertext())) if child is not None else ""


def us_section_content(section: ET.Element) -> str:
    pieces: list[str] = []
    for child in section:
        name = child.tag.rsplit("}", 1)[-1]
        if name == "notes":
            continue
        text = compact_text("".join(child.itertext()))
        if text:
            pieces.append(text)
    return "\n".join(pieces)


def us_title_name(root: ET.Element, title_number: str) -> str:
    title = root.find(f"{USLM}title")
    heading = direct_child_text(title, "heading") if title is not None else ""
    base = f"United States Code Title {title_number}"
    return f"{base} — {heading.title()}" if heading else base


def walk_us_sections(element: ET.Element, hierarchy: tuple[str, ...] = ()) -> Iterator[tuple[ET.Element, tuple[str, ...]]]:
    local_name = element.tag.rsplit("}", 1)[-1]
    next_hierarchy = hierarchy
    if local_name in {"subtitle", "chapter", "subchapter", "part", "subpart"}:
        number = direct_child_text(element, "num")
        heading = direct_child_text(element, "heading")
        label = " ".join(value for value in (number, heading) if value)
        if label:
            next_hierarchy = (*hierarchy, label)
    if local_name == "section":
        yield element, next_hierarchy
        return
    for child in element:
        yield from walk_us_sections(child, next_hierarchy)


def us_rows(directory: Path, release_point: str) -> Iterator[dict[str, Any]]:
    occurrences: Counter[str] = Counter()
    for file in sorted(directory.glob("usc*.xml")):
        root = ET.parse(file).getroot()
        meta = root.find(f"{USLM}meta")
        title_number = direct_child_text(meta, "docNumber") if meta is not None else re.sub(r"\D", "", file.stem)
        law_name = us_title_name(root, title_number)
        for section, hierarchy in walk_us_sections(root):
            section_number = clean_text(section.findtext(f"{USLM}num"))
            number_element = section.find(f"{USLM}num")
            number_value = clean_text(number_element.get("value")) if number_element is not None else ""
            heading = direct_child_text(section, "heading")
            identifier = clean_text(section.get("identifier")) or f"/us/usc/t{title_number}/s{number_value}"
            occurrence_key = f"{file.name}:{identifier}"
            occurrence = occurrences[occurrence_key]
            occurrences[occurrence_key] += 1
            source_item_id = hashlib.sha256(f"{occurrence_key}#{occurrence}".encode("utf-8")).hexdigest()
            content = us_section_content(section)
            if not number_value and not content:
                continue
            source_url = (
                "https://uscode.house.gov/view.xhtml?req=granuleid:USC-prelim-"
                f"title{title_number}-section{number_value}&num=0&edition=prelim"
            )
            yield {
                "law_name": law_name,
                "category": "美国法典",
                "chapter": " · ".join(hierarchy) or None,
                "article_no": section_number or f"§ {number_value}",
                "content": content,
                "effective_date": None,
                "issuing_authority": "Office of the Law Revision Counsel, U.S. House of Representatives",
                "jurisdiction": "US",
                "language_code": "en",
                "status": f"current-through-{release_point}",
                "source_dataset": f"US-Code-{release_point}",
                "source_item_id": source_item_id,
                "source_url": source_url,
                "license_name": "US-Government-Work-Public-Domain",
                "promulgation_date": None,
                "metadata": {
                    "identifier": identifier,
                    "sourceFile": file.name,
                    "duplicateOccurrence": occurrence,
                    "titleNumber": title_number,
                    "sectionNumber": number_value,
                    "heading": heading,
                    "releasePoint": release_point,
                },
            }


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--china-dir", type=Path, required=True)
    parser.add_argument("--uk-parquet", type=Path, required=True)
    parser.add_argument("--eu-parquet", type=Path, action="append", required=True)
    parser.add_argument("--us-dir", type=Path, required=True)
    parser.add_argument("--us-release-point", default="119-138")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    datasets = {
        "Chinese-Law-Corpus": write_sql(args.output_dir / "lexaid-laws-cn.sql.gz", china_rows(args.china_dir)),
        f"US-Code-{args.us_release_point}": write_sql(
            args.output_dir / "lexaid-laws-us.sql.gz", us_rows(args.us_dir, args.us_release_point)
        ),
        "EURLEX57K": write_sql(args.output_dir / "lexaid-laws-eu.sql.gz", eu_rows(args.eu_parquet)),
        "UK-LexAPI-2026-11-01": write_sql(
            args.output_dir / "lexaid-laws-uk.sql.gz", uk_rows(args.uk_parquet)
        ),
    }
    licenses = {
        "Chinese-Law-Corpus": "CC0-1.0",
        f"US-Code-{args.us_release_point}": "US-Government-Work-Public-Domain",
        "EURLEX57K": "CC-BY-SA-4.0",
        "UK-LexAPI-2026-11-01": "Open-Government-Licence-3.0",
    }
    manifest = {
        "generatedBy": "scripts/build-legal-code-datasets.py",
        "datasets": datasets,
        "licenses": licenses,
        "totalRecords": sum(item["records"] for item in datasets.values()),
    }
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
