"""Recover PDF page boundaries for the exact text included in the Yale snapshot."""

import argparse
import gzip
import hashlib
import json
import struct
from pathlib import Path

import pymupdf


HERE = Path(__file__).resolve().parent
OUTPUT = HERE.parents[2] / "frontend/src/views/viewpoints/yale-page-boundaries.js"


def page_map(content, pages):
    if not pages or not all(pages) or "\n\n".join(pages) != content:
        raise ValueError("PDF text differs from the archived text")
    # The reader slices JS strings by UTF-16 code unit. Offsets exclude the
    # two newlines inserted between PDF pages by texts.py.
    ends = []
    offset = 0
    for page in pages:
        offset += len(page.encode("utf-16-le")) // 2
        ends.append(offset)
        offset += 2
    checksum = 2166136261
    for (unit,) in struct.iter_unpack("<H", content.encode("utf-16-le")):
        checksum = ((checksum ^ unit) * 16777619) & 0xffffffff
    return {"length": ends[-1], "ends": ends, "checksum": f"{checksum:08x}"}


def build(cache):
    sources = json.loads((HERE / "text-sources.json").read_text(encoding="utf-8"))
    with gzip.open(HERE / "records.json.gz", "rt", encoding="utf-8") as stream:
        records = [row for row in json.load(stream) if row["content"]]
    if {row["source_item_id"] for row in records} != sources.keys():
        raise ValueError("The archived PDF list differs from the archived texts")
    result = {}
    for row in records:
        item_id = row["source_item_id"]
        digest = sources[item_id]["sha256"]
        data = (cache / f"{digest}.pdf").read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError(f"PDF checksum mismatch for {item_id}")
        with pymupdf.open(stream=data, filetype="pdf") as doc:
            pages = [p.get_text(sort=True).strip() for p in doc]
        try:
            result[row["source_url"]] = page_map(row["content"], pages)
        except ValueError as exc:
            raise ValueError(f"{item_id}: {exc}") from exc
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache-dir", required=True, type=Path, help="Cache created by collect.py")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    result = build(args.cache_dir)
    entries = [f"  {json.dumps(url)}: {json.dumps(result[url], separators=(',', ':'))}"
               for url in sorted(result)]
    args.output.write_text("// Generated by datasets/legal-papers/yale/page_boundaries.py\n"
                           + "export default {\n" + ",\n".join(entries) + "\n}\n", encoding="utf-8")
    print(f"Verified {len(result)} archived PDFs and {sum(len(row['ends']) for row in result.values())} pages.")
