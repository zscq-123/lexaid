CREATE TABLE IF NOT EXISTS user_profile (
  user_id                  BIGINT       NOT NULL,
  gender                   VARCHAR(16)  NOT NULL DEFAULT 'UNSPECIFIED',
  phone                    VARCHAR(24)  DEFAULT NULL,
  exam_goal                VARCHAR(24)  NOT NULL DEFAULT 'UNDECIDED',
  legal_exam_attempts      TINYINT UNSIGNED DEFAULT NULL,
  master_exam_attempts     TINYINT UNSIGNED DEFAULT NULL,
  legal_exam_year          SMALLINT UNSIGNED DEFAULT NULL,
  master_exam_year         SMALLINT UNSIGNED DEFAULT NULL,
  legal_exam_stage         VARCHAR(24)  DEFAULT NULL,
  master_exam_stage        VARCHAR(24)  DEFAULT NULL,
  preparation_status       VARCHAR(24)  DEFAULT NULL,
  created_at               DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at               DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id),
  CONSTRAINT fk_user_profile_user FOREIGN KEY (user_id) REFERENCES `user` (id) ON DELETE CASCADE,
  CHECK (gender IN ('UNSPECIFIED','MALE','FEMALE')),
  CHECK (exam_goal IN ('UNDECIDED','LEGAL_EXAM','LAW_MASTER','BOTH')),
  CHECK (legal_exam_attempts IS NULL OR legal_exam_attempts <= 99),
  CHECK (master_exam_attempts IS NULL OR master_exam_attempts <= 99),
  CHECK (legal_exam_year IS NULL OR legal_exam_year BETWEEN 2000 AND 2100),
  CHECK (master_exam_year IS NULL OR master_exam_year BETWEEN 2000 AND 2100),
  CHECK (legal_exam_stage IS NULL OR legal_exam_stage IN ('FOUNDATION','INTENSIVE','SPRINT','EXAM_READY','FINISHED')),
  CHECK (master_exam_stage IS NULL OR master_exam_stage IN ('FOUNDATION','INTENSIVE','SPRINT','EXAM_READY','FINISHED')),
  CHECK (preparation_status IS NULL OR preparation_status IN ('NOT_STARTED','PREPARING','PAUSED','COMPLETED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
